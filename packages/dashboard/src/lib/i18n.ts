export type TKey = keyof typeof T.ar

export type TVars = Record<string, string | number>

function interpolate(raw: string, vars?: TVars): string {
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}

function lookup(lang: Lang, key: TKey): string {
  return (T[lang] as Record<string, string>)[key] ?? (T.ar as Record<string, string>)[key] ?? key
}

export function useT(): (key: TKey, vars?: TVars) => string {
  const lang = useUIStore((s) => s.lang)
  return (key: TKey, vars?: TVars): string => interpolate(lookup(lang, key), vars)
}

export function t(lang: Lang, key: TKey, vars?: TVars): string {
  return interpolate(lookup(lang, key), vars)
}

export function formatRelativeLang(dateStr: string, lang: Lang): string {
  const diff = (Date.now() - new Date(dateStr).getTime()) / 1000
  if (lang === 'en') {
    if (diff < 60)    return 'Just now'
    if (diff < 3600)  return `${Math.floor(diff / 60)}m ago`
    if (diff < 86400) return `${Math.floor(diff / 3600)}h ago`
    return new Date(dateStr).toLocaleDateString('en-US', { day: '2-digit', month: 'short' })
  }
  if (diff < 60)    return 'الآن'
  if (diff < 3600)  return `منذ ${Math.floor(diff / 60)} د`
  if (diff < 86400) return `منذ ${Math.floor(diff / 3600)} س`
  return new Date(dateStr).toLocaleDateString('ar-EG', { day: '2-digit', month: 'short' })
}
